/**
 * Derives repository facts from the filesystem into src/data/repo-facts.json.
 *
 * Same rule as the results binding: a number that can drift must not be typed.
 * "Forty-five entries" was already stale -- there are 48 numbered changelog
 * fragments -- and because narration is baked into audio, a drifting number in
 * the voice cannot be corrected without re-recording. So drifting numbers live
 * on screen, bound to this file; the voice says only what stays true.
 *
 * Run before rendering: node capture/collect-repo-facts.mjs
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const VIDEO = resolve(HERE, "..");
const REPO = resolve(VIDEO, "..");

const changelogFragments = readdirSync(join(REPO, "docs", "changelog")).filter((f) =>
  /^\d+-.*\.md$/.test(f),
);
const testFiles = readdirSync(join(REPO, "tests")).filter((f) => /^test_.*\.py$/.test(f));

const changelog = readFileSync(join(REPO, "docs", "CHANGELOG.md"), "utf8").split("\n");
const redteam = readFileSync(join(REPO, "docs", "RED-TEAM.md"), "utf8").split("\n");

/**
 * Rows of the slice log -- the five tables headed
 * "Stage | What was tried and why | Evidence | Decision / learning".
 * Counted rather than typed: docs/CHANGELOG.md is eight interleaved tables and
 * the total moves whenever a slice lands.
 */
const SLICE_HEADER = /^\|\s*Stage\s*\|\s*What was tried and why\s*\|/;
let inSlice = false;
let sliceRows = 0;
for (const line of changelog) {
  if (SLICE_HEADER.test(line)) { inSlice = true; continue; }
  if (inSlice) {
    if (/^\|\s*-+\s*\|/.test(line)) continue;      // separator
    if (/^\|/.test(line)) { sliceRows += 1; continue; }
    inSlice = false;                                  // table ended
  }
}

/**
 * Claims the red team broke. Counted off the summary table rather than trusting
 * the word "twelve" in prose -- that count is the whole point of the beat, and
 * a stale one would be the exact failure the video is about.
 */
// NB: row 12 reads "**BROKEN in the README**", so the verdict is matched by
// prefix. Requiring the closing asterisks silently counted 11 and would have
// put a wrong number on screen in the beat about wrong numbers.
const verdict = (re) =>
  redteam.filter((l) => /^\|\s*\d+\s*\|/.test(l) && re.test(l)).length;
const brokenClaims = verdict(/\*\*BROKEN/);
const survivedClaims = verdict(/\*\*SURVIVES/);
const partialClaims = verdict(/\*\*(PARTIAL|WEAK)/);

/**
 * Collected test count. pytest collection needs the full extras venv and takes
 * ~20s, so it only runs with --tests; otherwise the previous value is carried
 * forward. `testFiles` alone was misleading -- 44 files, 591 tests.
 */
const OUT = join(VIDEO, "src", "data", "repo-facts.json");
const previous = existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8")) : {};
let testsCollected = previous.testsCollected ?? null;

if (process.argv.includes("--tests")) {
  const tree = process.env.ASSAY_CAPTURE_TREE ?? resolve(VIDEO, "..", "..", "assay-video-capture");
  const out = execFileSync(
    "uv",
    ["run", "--extra", "dev", "--extra", "adapters", "--extra", "sweep", "--extra", "openenv",
     "pytest", "--collect-only", "-q"],
    { cwd: tree, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
  );
  // pytest -q prints one "path: N" line per file, not one line per test id.
  testsCollected = out
    .split("\n")
    .map((l) => /^tests\/.*: (\d+)$/.exec(l.trim()))
    .filter(Boolean)
    .reduce((a, m) => a + Number(m[1]), 0);
}

const facts = {
  _comment:
    "Generated by capture/collect-repo-facts.mjs. Do not edit by hand -- re-run it.",
  generatedFrom: "filesystem",
  changelogFragments: changelogFragments.length,
  changelogSliceRows: sliceRows,
  testFiles: testFiles.length,
  testsCollected,
  redTeamBrokenClaims: brokenClaims,
  redTeamSurvivedClaims: survivedClaims,
  redTeamPartialClaims: partialClaims,
};

writeFileSync(OUT, `${JSON.stringify(facts, null, 2)}\n`);
console.log(
  `changelog fragments: ${facts.changelogFragments} · slice rows: ${facts.changelogSliceRows} · ` +
    `test files: ${facts.testFiles} · red-team broken: ${facts.redTeamBrokenClaims} · ` +
    `survived: ${facts.redTeamSurvivedClaims} · partial: ${facts.redTeamPartialClaims} · ` +
    `tests: ${facts.testsCollected ?? "(pass --tests)"}`,
);
