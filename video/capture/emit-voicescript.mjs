/**
 * Emits VOICE-SCRIPT.md from narration.json.
 *
 * The two used to be kept in step by hand. They matched, but only because
 * nobody slipped -- and this project's whole argument is that "it matched when
 * I checked" is not a property of a system. Generating it makes the match
 * structural: the file cannot drift from the script it is generated from.
 *
 * Usage: node capture/emit-voicescript.mjs [block ...]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const VIDEO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const narration = JSON.parse(readFileSync(join(VIDEO, "src", "data", "narration.json"), "utf8"));

const VOICE = "pVnrL6sighQX7hVz89cp";
const SPEED = "1.05";

/** Beat-tagged cues start a new paragraph, so the pause is real. */
export const spokenOf = (cues) =>
  cues
    .map((c, i) => (c.beat && i ? "\n\n" : i ? " " : "") + (c.spoken ?? c.text))
    .join("");

/**
 * Guarded: the write used to run on import, so `import { spokenOf }` silently
 * regenerated the file with all seven blocks and clobbered a two-block script.
 */
const main = () => {
  const blocks = Object.keys(narration).filter((k) => !k.startsWith("_"));
  const wanted = process.argv.slice(2).filter((a) => !a.startsWith("--"));
  const todo = wanted.length ? blocks.filter((b) => wanted.includes(b)) : blocks;

  const body = todo.map((k) => {
    const t = spokenOf(narration[k]);
    return [
      `## ${k}  →  \`public/voice/${k}.mp3\``,
      "",
      `*${t.split(/\s+/).length} words · ${t.length} chars*`,
      "",
      "```text",
      t,
      "```",
      "",
      "---",
      "",
    ].join("\n");
  });

  const chars = todo.reduce((a, k) => a + spokenOf(narration[k]).length, 0);
  const head = [
    `# Narration — ${todo.length} block${todo.length === 1 ? "" : "s"} to record`,
    "",
    `Voice \`${VOICE}\`  ·  **Speed ${SPEED}**  ·  eleven_multilingual_v2`,
    "",
    "Generated by `node capture/emit-voicescript.mjs` — do not edit by hand.",
    "",
    "Blank lines are real pauses. Respellings (`Ass-ay`, `Q-A's`, `yes-no`, `S-W-E bench`,",
    "`Open env's`, `Science Agent Bench`) are deliberate; the captions show the written forms.",
    "",
    "---",
    "",
  ].join("\n");

  writeFileSync(join(VIDEO, "VOICE-SCRIPT.md"), head + body.join("") + `**${chars} characters.**\n`);
  console.log(`${todo.join(", ")} -> VOICE-SCRIPT.md (${chars} chars)`);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
